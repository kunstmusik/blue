#!/usr/bin/env node
/**
 * Deterministic bundler for the Blue-maintained modern BlueX7 orchestra.
 *
 * Reads packages/blue-data/resources/blue-x7-modern/bluex7.orc (package-relative;
 * this script never accesses the transient precursor checkout) and emits the
 * browser-safe TypeScript module
 * packages/blue-data/src/instruments/blue-x7/modern-orchestra.generated.ts.
 *
 * Modes:
 *   (default)      regenerate the module and refresh the current digests in
 *                  provenance.json
 *   --check        verify the generated module is byte-identical and the
 *                  recorded digests match the files; exits non-zero without
 *                  writing otherwise
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = join(SCRIPT_DIR, '..');
const RESOURCE_DIR = join(PACKAGE_ROOT, 'resources', 'blue-x7-modern');
const ORC_PATH = join(RESOURCE_DIR, 'bluex7.orc');
const PROVENANCE_PATH = join(RESOURCE_DIR, 'provenance.json');
const GENERATED_PATH = join(PACKAGE_ROOT, 'src', 'instruments', 'blue-x7', 'modern-orchestra.generated.ts');

/** Escape Csound text for a TypeScript template literal. */
export function escapeOrcForTemplateLiteral(text) {
  return text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

/** Render the deterministic generated-module text for one orchestra source. */
export function renderGeneratedModule(orcText, orcSha256) {
  const header = [
    '// GENERATED by scripts/generate-blue-x7-modern-orchestra.mjs — DO NOT EDIT BY HAND.',
    '// Source: packages/blue-data/resources/blue-x7-modern/bluex7.orc',
    `// Source sha256: ${orcSha256}`,
    '// Regenerate with: pnpm --filter @blue/data generate:blue-x7',
    '',
    '/**',
    ' * The modern BlueX7 synthesis module (Csound orchestra text). This is the',
    ' * Blue-maintained adaptation of the reviewed precursor renderer; provenance',
    ' * and attribution live in packages/blue-data/resources/blue-x7-modern/.',
    ' * Browser-safe: this module contains only this string.',
    ' */',
    'export const BLUE_X7_MODERN_ORCHESTRA = `',
  ];
  const body = escapeOrcForTemplateLiteral(orcText);
  return `${header.join('\n')}${body}\`;\n`;
}

function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function fail(message) {
  console.error(`generate:blue-x7: ${message}`);
  process.exitCode = 1;
}

export function main(argv) {
  const checkOnly = argv.includes('--check');
  const orcText = readFileSync(ORC_PATH, 'utf8');
  const orcDigest = sha256(orcText);
  const provenance = readJson(PROVENANCE_PATH);

  if (provenance.current.orchestra.sha256 !== orcDigest) {
    if (checkOnly) {
      return fail(
        `provenance.json current orchestra digest ${provenance.current.orchestra.sha256} does not match ${ORC_PATH} (${orcDigest}); run generate:blue-x7 after reviewing the change.`,
      );
    }
    provenance.current.orchestra.sha256 = orcDigest;
  }

  const generated = renderGeneratedModule(orcText, orcDigest);

  if (checkOnly) {
    let existing;
    try {
      existing = readFileSync(GENERATED_PATH, 'utf8');
    } catch {
      return fail(`missing generated module ${GENERATED_PATH}; run generate:blue-x7.`);
    }
    if (existing !== generated) {
      return fail(`stale generated module ${GENERATED_PATH}; run generate:blue-x7.`);
    }
    const recordedModuleDigest = provenance.current.generatedModule.sha256;
    if (recordedModuleDigest !== sha256(generated)) {
      return fail('provenance.json generated-module digest does not match the generated module.');
    }
    console.log('generate:blue-x7: check passed.');
    return;
  }

  const previous = (() => {
    try {
      return readFileSync(GENERATED_PATH, 'utf8');
    } catch {
      return null;
    }
  })();
  if (previous === generated && provenance.current.orchestra.sha256 === orcDigest
    && provenance.current.generatedModule.sha256 === sha256(generated)) {
    console.log('generate:blue-x7: output already up to date.');
    return;
  }

  writeFileSync(GENERATED_PATH, generated);
  provenance.current.generatedModule.sha256 = sha256(generated);
  writeFileSync(PROVENANCE_PATH, `${JSON.stringify(provenance, null, 2)}\n`);
  console.log(`generate:blue-x7: wrote ${GENERATED_PATH}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}
